"""### 10.2 Por mês e por tipo de dia

O tipo de dia é classificado **a partir da potência observada, só para a análise** (nunca como entrada de um modelo):

* `ratio` = energia do dia (horas 06–18 UTC) / envolvente da energia diária (percentil 95 numa janela de 31 dias) — mede quão perto o dia está do melhor dia da época;
* `TV` = variação total da potência ao longo do dia / (2 × máximo) — vale ≈ 1 numa curva suave e sobe com as nuvens passageiras.

**clear**: ratio ≥ 0.85 e TV ≤ 1.15 · **overcast**: ratio < 0.30 · **variable**: os restantes. Só entram dias com as 13 horas medidas. Os limiares estão em `SKY_PARAMS`.
"""

SKY_PARAMS = dict(clear_ratio=0.85, clear_tv=1.15, overcast_ratio=0.30)

def classify_days(hourly_power, p=SKY_PARAMS):
    d = hourly_power[(hourly_power.index.hour >= 6) & (hourly_power.index.hour <= 18)]
    g = d.groupby(d.index.normalize())
    valid = g.count() == 13
    energy = g.sum().where(valid)
    env = energy.rolling(31, center=True, min_periods=10).quantile(0.95)
    tv = g.apply(lambda s: np.abs(np.diff(s.values)).sum() / (2 * np.nanmax(s.values)) if np.nanmax(s.values) > 0 else np.nan)
    days = pd.DataFrame({'energy': energy, 'ratio': energy / env, 'TV': tv.where(valid)}).dropna()
    days['sky'] = np.where((days['ratio'] >= p['clear_ratio']) & (days['TV'] <= p['clear_tv']), 'clear',
                    np.where(days['ratio'] < p['overcast_ratio'], 'overcast', 'variable'))
    return days

