"""---
## 4. Construção das amostras de treino e de teste

**Uma linha = um par (run k, lead L)** que descreve a hora [t, t+1h[ com t = k + L. Todas as features desta linha usam só informação disponível à emissão do run k:

* valores WRF do próprio run k em t e em t+1h (o lead L+1 do mesmo run; por isso carregamos os 72 leads);
* valores WRF dos runs anteriores para a mesma hora: o run k−1 (lead L+24) e o run k−2 (lead L+48);
* calendário de t.

Os runs anteriores dos primeiros runs de teste (1–2 de janeiro de 2026) estão no ficheiro de treino, por isso as features de NWP são calculadas sobre **treino + teste concatenados** (só as variáveis WRF; a potência do teste não existe e nunca é usada).

**Decisões tuas** (variáveis no início da célula 4.1): quantos leads entram no treino (`TRAIN_LEADS` = 24 ou 72; se 72, acrescenta `lead_time` aos feature sets) e como tratar as linhas problemáticas da secção 2 (`EXCLUDE_ROWS`).
"""

# 4.1 Configuração das amostras
