class SubsetEnsemble(BaseEstimator, RegressorMixin):
    '''Média ponderada de modelos, cada um com o seu feature set. Recebe um DataFrame com a união das colunas.'''
    def __init__(self, members=None, weights=None):
        self.members, self.weights = members, weights
    def fit(self, X, y):
        self.fitted_ = [(clone(est).fit(X[cols], y), cols) for est, cols in self.members]
        return self
    def predict(self, X):
        preds = np.column_stack([est.predict(X[cols]) for est, cols in self.fitted_])
        return preds @ np.asarray(self.weights)

