# 4.2 Função que constrói TODAS as features candidatas a partir do NWP (sem usar potência)
def build_features(nwp):
    f = nwp.sort_values(['timerequests', 'lead_time']).reset_index(drop=True).copy()
    g = f.groupby('timerequests')

    # --- valores em t+1h do MESMO run (lead L+1) e médias de [t, t+1h] ---
    for p in POINTS:
        f[f'swflx_{p}_next'] = g[f'swflx_{p}'].shift(-1)
        f[f'cft_{p}_next']   = g[f'cft_{p}'].shift(-1)
        f[f'swflx_avg_{p}']  = (f[f'swflx_{p}'] + f[f'swflx_{p}_next']) / 2
        f[f'cft_avg_{p}']    = (f[f'cft_{p}'] + f[f'cft_{p}_next']) / 2

    # --- informação espacial (5 pontos da grelha) ---
    sw = f[[f'swflx_avg_{p}' for p in POINTS]]; cf = f[[f'cft_avg_{p}' for p in POINTS]]
    f['swflx_avg_mean'], f['swflx_avg_std'] = sw.mean(axis=1), sw.std(axis=1)
    f['swflx_avg_min'],  f['swflx_avg_max'] = sw.min(axis=1),  sw.max(axis=1)
    f['cft_avg_mean'],   f['cft_avg_std']   = cf.mean(axis=1), cf.std(axis=1)

    # --- calendário (hora e dia do ano de t) ---
    f['hour']  = f['timestamp_utc'].dt.hour
    f['month'] = f['timestamp_utc'].dt.month
    f['doy']   = f['timestamp_utc'].dt.dayofyear
    f['hour_sin'], f['hour_cos'] = np.sin(2 * np.pi * f['hour'] / 24), np.cos(2 * np.pi * f['hour'] / 24)
    f['doy_sin'],  f['doy_cos']  = np.sin(2 * np.pi * f['doy'] / 365.25), np.cos(2 * np.pi * f['doy'] / 365.25)
    for h in range(24):
        f[f'hour_{h}'] = (f['hour'] == h).astype(int)            # one-hot da hora (UTC)

    # --- runs anteriores: mesma hora prevista pelos runs k-1 (lead L+24) e k-2 (lead L+48) ---
    look = f[['timerequests', 'timestamp_utc', 'swflx_3', 'cft_3']]
    for days, tag in [(1, 'prev24'), (2, 'prev48')]:
        key = f[['timerequests', 'timestamp_utc']].copy()
        key['timerequests'] = key['timerequests'] - pd.Timedelta(days=days)
        old = key.merge(look, on=['timerequests', 'timestamp_utc'], how='left')
        f[f'swflx_3_{tag}'] = old['swflx_3'].values
        f[f'cft_3_{tag}']   = old['cft_3'].values
    # sem run anterior (só os 2 primeiros runs do treino): usa o valor do próprio run
    f['no_prev_run'] = f['swflx_3_prev48'].isna().astype(int)
    for tag in ('prev24', 'prev48'):
        f[f'swflx_3_{tag}'] = f[f'swflx_3_{tag}'].fillna(f['swflx_3'])
        f[f'cft_3_{tag}']   = f[f'cft_3_{tag}'].fillna(f['cft_3'])

    # --- variáveis derivadas (candidatas a FS5) ---
    f['swflx_trend']    = f['swflx_3_next'] - f['swflx_3']                    # variação dentro da hora
    f['swflx_x_clear']  = f['swflx_avg_3'] * (1 - f['cft_avg_3'])             # irradiância x céu limpo
    f['swflx_d24']      = f['swflx_3'] - f['swflx_3_prev24']                  # mudança face ao run anterior
    f['swflx_runs_std'] = f[['swflx_3', 'swflx_3_prev24', 'swflx_3_prev48']].std(axis=1)
    f['night']          = ((f['swflx_3'] == 0) & (f['swflx_3_next'] == 0)).astype(int)
    return f

