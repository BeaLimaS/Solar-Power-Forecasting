def read_dataset(path):
    '''Lê um CSV do projeto (sep=';') e converte as colunas de tempo (UTC, dd/mm/yyyy hh:mm).'''
    df = pd.read_csv(path, sep=';')
    df.columns = [c.strip() for c in df.columns]
    for c in ('timerequests', 'timestamp_utc'):
        if c in df.columns:
            df[c] = pd.to_datetime(df[c], format='%d/%m/%Y %H:%M')
    return df


def metrics(y_true, y_pred, mse_b1=None, pmax=PMAX):
    '''MSE, RMSE, NRMSE (%), MAE, bias (positivo = sobrestima) e skill vs B1 (%).
    Ignora pares com NaN. Se mse_b1 for dado, calcula Skill = (1 - MSE/MSE_B1) * 100.'''
    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)
    ok = ~(np.isnan(y_true) | np.isnan(y_pred))
    e = y_pred[ok] - y_true[ok]
    mse = float(np.mean(e ** 2))
    out = {
        'N': int(ok.sum()),
        'MSE': mse,
        'MSE_1e6': mse / 1e6,
        'RMSE': float(np.sqrt(mse)),
        'NRMSE_%': float(100 * np.sqrt(mse) / pmax),
        'MAE': float(np.mean(np.abs(e))),
        'bias': float(np.mean(e)),
    }
    if mse_b1 is not None:
        out['Skill_vs_B1_%'] = float(100 * (1 - mse / mse_b1))
    return out


def blocked_month_cv(df, fit_predict, time_col='timestamp_utc', gap_hours=0):
    '''Validação cronológica em blocos mensais: para cada mês, treina nos restantes e prevê esse mês.
    - O mês é o da hora prevista (timestamp_utc), logo a mesma hora-alvo (leads h, h+24, h+48)
      nunca está em treino e validação ao mesmo tempo.
    - gap_hours > 0 exclui do treino as linhas junto às fronteiras do bloco de validação.
    - fit_predict(df_train, df_val) -> array com as previsões para df_val.
    Devolve uma Series (índice de df) com as previsões out-of-fold.'''
    month = df[time_col].dt.month
    oof = pd.Series(np.nan, index=df.index)
    gap = pd.Timedelta(hours=gap_hours)
    for m in sorted(month.unique()):
        val = month == m
        t0, t1 = df.loc[val, time_col].min(), df.loc[val, time_col].max()
        near = (df[time_col] >= t0 - gap) & (df[time_col] <= t1 + gap)
        tr = ~val & ~near
        oof.loc[val] = np.asarray(fit_predict(df[tr], df[val]))
    return oof


def plot_scatter_obs_pred(y_true, y_pred, title='Previsto vs observado'):
    lim = max(np.nanmax(y_true), np.nanmax(y_pred))
    fig, ax = plt.subplots(figsize=(5, 5))
    ax.scatter(y_true, y_pred, s=4, alpha=0.3)
    ax.plot([0, lim], [0, lim], 'r--', lw=1)
    ax.set_xlabel('Observado'); ax.set_ylabel('Previsto'); ax.set_title(title)
    plt.show()


def plot_error_by(group, y_true, y_pred, xlabel='', title=''):
    '''RMSE por grupo (ex.: lead_time ou hora do dia).'''
    d = pd.DataFrame({'g': np.asarray(group), 'e2': (np.asarray(y_pred) - np.asarray(y_true)) ** 2})
    rmse = d.groupby('g')['e2'].mean() ** 0.5
    rmse.plot(marker='o')
    plt.xlabel(xlabel); plt.ylabel('RMSE'); plt.title(title)
    plt.show()

