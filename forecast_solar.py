register('B1', 'Regressão linear (referência; leads 1-24, negativos = 0)', 'FS1',
         cv_predict(ClipNegative(LinearRegression()), FEATURE_SETS['FS1'], train_leads=24))
print('B0 e B1 calculados:', {k: round(((v['oof'] - y_val) ** 2).mean() / 1e6, 3) for k, v in results.items()}, '(MSE em 10^6 kW^2)')

