"""---
## 6. Esquema de validação cronológica

**Validação cruzada em blocos mensais** (como no modelo da disciplina): 12 folds, em cada um o mês de validação é o mês do **run** (um run nunca é partido) e o treino usa os outros 11 meses. A validação é sempre feita nas linhas de leads 1–24 com potência medida (noite incluída).

Cuidados implementados:

* se `TRAIN_LEADS = 72`, as linhas de treino cuja hora (`timestamp_utc`) cai na hora de validação são retiradas do treino (a mesma hora aparece em 3 runs);
* linhas de treino com NaN nas features (ex.: `*_next` no lead 72) são retiradas do ajuste;
* escalonamento e outras transformações devem ir **dentro** do modelo (`Pipeline`), para serem ajustados só no treino de cada fold.
"""

from sklearn.base import clone

def month_folds(train_leads=TRAIN_LEADS):
    '''Lista de (mês, índices de treino, índices de validação) da validação em blocos mensais.'''
    folds = []
    for m in sorted(data_all['run_month'].unique()):
        va = data_all.index[(data_all['run_month'] == m) & (data_all['lead_time'] <= MAX_LEAD)]
        hours_val = set(data_all.loc[va, 'timestamp_utc'])
        tr_mask = ((data_all['run_month'] != m) & (data_all['lead_time'] <= train_leads)
                   & ~data_all['timestamp_utc'].isin(hours_val))
        folds.append((m, data_all.index[tr_mask], va))
    return folds

def cv_predict(model, feats, train_leads=TRAIN_LEADS, folds=None):
    '''Previsões out-of-fold para as linhas de data24. `model` é um estimador (ou Pipeline) do scikit-learn.
    Em cada fold o modelo é clonado e ajustado só com o treino desse fold.'''
    folds = folds or month_folds(train_leads)
    oof = pd.Series(np.nan, index=data_all.index)
    for m, tr, va in folds:
        tr = tr[data_all.loc[tr, feats].notna().all(axis=1).values]
        est = clone(model).fit(data_all.loc[tr, feats], data_all.loc[tr, 'power'])
        oof.loc[va] = est.predict(data_all.loc[va, feats])
    return oof.loc[data24.index]

