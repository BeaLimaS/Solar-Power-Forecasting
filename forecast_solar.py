"""### 8.4 M7 (média dos modelos) e pós-processamento

O M7 é a média das previsões out-of-fold de M4, M5 e M6 (cada modelo foi ajustado só com o treino de cada fold, por isso a média também é *out-of-sample*). Para o ajuste final, a classe `SubsetEnsemble` ajusta cada componente com o seu feature set e faz a média. Em `ENS_IDS` e `ENS_WEIGHTS` escolhes os componentes e os pesos.

As linhas `-PP` aplicam o pós-processamento (noite = 0 quando `swflx_3` e `swflx_3_next` são 0, e clip a [0, PMAX]).
"""

ENS_IDS = ['M4', 'M5', 'M6']
