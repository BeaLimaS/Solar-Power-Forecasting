def train_vs_cv(model, fs, train_leads=None, id_=None):
    '''MSE (10^6 kW^2) no treino (modelo ajustado com TODO o treino, avaliado nas mesmas linhas) vs MSE na CV.
    Uma grande diferença sugere overfitting.'''
    tl = TRAIN_LEADS if train_leads is None else train_leads
    feats = FEATURE_SETS[fs]
    tr = data_all[data_all['lead_time'] <= tl]
    tr = tr[tr[feats].notna().all(axis=1)]
    est = clone(model).fit(tr[feats], tr['power'])
    in_mse = float(((est.predict(data24[feats]) - y_val) ** 2).mean()) / 1e6
    oof = results[id_]['oof'] if id_ in results else cv_predict(model, feats, train_leads=tl)   # reutiliza a CV já feita
    cv_mse = float(((oof - y_val) ** 2).mean()) / 1e6
    return {'MSE treino': in_mse, 'MSE CV': cv_mse, 'rácio CV/treino': cv_mse / in_mse}

