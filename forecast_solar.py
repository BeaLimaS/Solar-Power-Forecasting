"""### 8.1 Procura de hiperparâmetros (como nos notebooks 03 e 04 do professor)

Para **procurar** hiperparâmetros usa-se uma validação mais barata: `GroupKFold` de 4 folds por mês do run (cada fold deixa de fora cerca de 3 meses inteiros). Os modelos finais são depois **avaliados** com os 12 folds mensais da secção 6, e é esses valores que vão para a matriz.

`random_search` amostra `n_iter` combinações de distribuições (`scipy.stats`) ou de listas e devolve a tabela ordenada pelo MSE. Como a procura e a avaliação usam os mesmos dados, os erros finais são ligeiramente otimistas (só a validação cruzada aninhada eliminaria este enviesamento): refere-o na discussão do *overfitting*.
"""

from sklearn.model_selection import GroupKFold, ParameterSampler
from scipy.stats import loguniform, randint, uniform

SEARCH_SPLITS = 4

def grouped_folds(n_splits=SEARCH_SPLITS, train_leads=None):
    '''Folds de procura: GroupKFold por mês do run (validação = leads 1-24; treino sem as horas de validação).'''
    tl = TRAIN_LEADS if train_leads is None else train_leads
    folds = []
    for k, (_, va_pos) in enumerate(GroupKFold(n_splits=n_splits).split(data24, groups=data24['run_month'])):
        months = set(data24['run_month'].iloc[va_pos])
        va = data_all.index[data_all['run_month'].isin(months) & (data_all['lead_time'] <= MAX_LEAD)]
        hours_val = set(data_all.loc[va, 'timestamp_utc'])
        tr = data_all.index[~data_all['run_month'].isin(months) & (data_all['lead_time'] <= tl)
                            & ~data_all['timestamp_utc'].isin(hours_val)]
        folds.append((sorted(months), tr, va))
    return folds

def random_search(estimator, dist, fs, n_iter=10, n_splits=SEARCH_SPLITS, seed=SEED, train_leads=None):
    '''Procura aleatória com a CV de procura. Devolve (tabela ordenada, melhores parâmetros).'''
    tl = TRAIN_LEADS if train_leads is None else train_leads
    folds = grouped_folds(n_splits, tl)
    rows = []
    for params in ParameterSampler(dist, n_iter=n_iter, random_state=seed):
        t0 = time.time()
        oof = cv_predict(clone(estimator).set_params(**params), FEATURE_SETS[fs], train_leads=tl, folds=folds)
        rows.append({**params, 'MSE (10^6 kW^2)': float(((oof - y_val) ** 2).mean()) / 1e6, 'tempo (s)': time.time() - t0})
    tbl = pd.DataFrame(rows).sort_values('MSE (10^6 kW^2)').reset_index(drop=True)
    best = {k: tbl.loc[0, k] for k in rows[0] if k not in ('MSE (10^6 kW^2)', 'tempo (s)')}
    best = {k: (v.item() if hasattr(v, 'item') else v) for k, v in best.items()}
    return tbl, best

